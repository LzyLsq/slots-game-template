import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import {compressWeb} from './webp.mjs';
const require=createRequire(import.meta.url);
const sharp=require('/Users/mengjunzhu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const dir=mkdtempSync(join(import.meta.dirname,'verification/webp-fixture-'));
const id='ab-image',native=join(dir,'assets/resources/native/ab'),imported=join(dir,'assets/resources/import/ab');
mkdirSync(native,{recursive:true});mkdirSync(imported,{recursive:true});
await sharp({create:{width:32,height:16,channels:3,background:'#ca9933'}}).jpeg().toFile(join(native,id+'.jpg'));
writeFileSync(join(imported,id+'.json'),JSON.stringify([1,0,0,['cc.ImageAsset'],0,[{fmt:'1',w:32,h:16},-1]]));
await sharp({create:{width:20,height:20,channels:4,background:{r:30,g:140,b:170,alpha:0.4}}}).png().toFile(join(dir,'foreground.png'));
await sharp({create:{width:24,height:12,channels:3,background:'#334466'}}).jpeg().toFile(join(dir,'background.jpeg'));
writeFileSync(join(dir,'index.html'),'<img src="foreground.png"><img src="background.jpeg">');
writeFileSync(join(dir,'engine.js'),'const generic = [".png", ".jpg"]; const explicit="assets/resources/native/ab/ab-image.jpg";');
const first=await compressWeb(dir);
assert.equal(first.count,3);
assert.equal(JSON.parse(readFileSync(join(imported,id+'.json')))[5][0].fmt,'4');
assert.match(readFileSync(join(dir,'index.html'),'utf8'),/foreground.webp/);
assert.match(readFileSync(join(dir,'index.html'),'utf8'),/background.webp/);
const engine=readFileSync(join(dir,'engine.js'),'utf8');
assert.ok(engine.includes('[".png", ".jpg"]'));
assert.ok(engine.includes('ab-image.webp'));
assert.ok(!existsSync(join(native,id+'.jpg')));
assert.equal((await compressWeb(dir)).count,0);
console.log('WebP PNG/JPEG metadata, references, exact-alpha and repeat-run checks passed.');
const staticDir=mkdtempSync(join(import.meta.dirname,'verification/webp-static-fixture-'));
mkdirSync(join(staticDir,'art'));
await sharp({create:{width:20,height:20,channels:4,background:{r:30,g:140,b:170,alpha:.4}}}).png().toFile(join(staticDir,'art/symbol-0.png'));
writeFileSync(join(staticDir,'app.js'),'const path=id=>`/art/symbol-${id}.png`; const crop=/symbol-\\d+\\.png$/;');
await compressWeb(staticDir,true);
const dynamic=readFileSync(join(staticDir,'app.js'),'utf8');
assert.ok(dynamic.includes('/art/symbol-${id}.webp'));
assert.ok(dynamic.includes('\\.webp$'));
assert.equal((await compressWeb(staticDir,true)).count,0);
assert.equal(readFileSync(join(staticDir,'app.js'),'utf8'),dynamic);
console.log('Pure-web dynamic image URL/crop patterns and repeat-run checks passed.');
