export const LANGUAGES = [
  { code: 'en', name: 'English' }, { code: 'zh-CN', name: '简体中文' },
  { code: 'zh-TW', name: '繁體中文' }, { code: 'ja', name: '日本語' }, { code: 'ko', name: '한국어' },
] as const;
export type Language = typeof LANGUAGES[number]['code'];
export const LANGUAGE_KEY = 'fortune-lantern-house-language-v1';
type StorageLike = Pick<Storage, 'getItem' | 'setItem'>;
let device: StorageLike | undefined;
let current: Language = 'en';
export function resolveLanguage(value: string | null | undefined): Language {
  if (/^zh/i.test(value || '')) return /TW|HK|Hant/i.test(value || '') ? 'zh-TW' : 'zh-CN';
  if (/^ja/i.test(value || '')) return 'ja';
  if (/^ko/i.test(value || '')) return 'ko';
  return 'en';
}
export function initializeLanguage(storage: StorageLike): void {
  device = storage;
  try { current = resolveLanguage(device.getItem(LANGUAGE_KEY) || 'en'); } catch { current = 'en'; }
}
export function language(): Language { return current; }
export function setLanguage(value: Language): void {
  current = LANGUAGES.some(item => item.code === value) ? value : 'en';
  try { device?.setItem(LANGUAGE_KEY, current); } catch { /* guest/private storage */ }
}
