export function translate(text,language=lang){
 if(language==='zh')return text;
 if(Object.hasOwn(dictionary,String(text)))return dictionary[String(text)];
 let s=String(text).replace(/(\d+)轴(\d+)行转轴/g,'$1 reels × $2 rows').replace(/第\s*(\d+)\s*天/g,'Day $1').replace(/每日宝藏 · 第/g,'Daily gift · Day ').replace(/」？/g,'”?');
 for(const [zh,en]of entries)s=s.split(zh).join(en);
 return s;
}
function localizeNode(node){
 if(node.nodeType===Node.TEXT_NODE){
  if(node.parentElement?.closest('[data-user-text],script,style,.notranslate'))return;
  const last=sources.get(node),now=node.nodeValue,source=last&&last.output===now?last.source:now;
  if(!/[\u4e00-\u9fff]/.test(source))return;
  const output=translate(source);sources.set(node,{source,output});if(now!==output)node.nodeValue=output;
 }else if(node.nodeType===Node.ELEMENT_NODE){
  if(node.matches('[data-user-text],script,style,.notranslate'))return;
  for(const key of ['aria-label','alt','placeholder','title'])if(node.hasAttribute(key)){
   const holder=node,all=sources.get(holder)||{},now=node.getAttribute(key),last=all[key],source=last&&last.output===now?last.source:now;
   if(!/[\u4e00-\u9fff]/.test(source))continue;
   const output=translate(source);all[key]={source,output};sources.set(holder,all);if(now!==output)node.setAttribute(key,output);
  }
  for(const child of node.childNodes)localizeNode(child);
 }
}
